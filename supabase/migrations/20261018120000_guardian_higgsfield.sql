-- Guardian video generation with each Guardian's OWN Higgsfield account (docs/higgsfield-integration.md).
-- Credentials are AES-GCM encrypted by the `higgsfield` Edge Function (HIGGSFIELD_ENCRYPTION_KEY) before they
-- are stored, and only that function (service role) ever reads them. A Guardian can see that they are
-- connected and the last four characters of their key id, never the key or secret.

create table if not exists public.guardian_higgsfield_connections (
  user_id uuid primary key references auth.users(id) on delete cascade,
  key_hint text not null,                 -- last 4 characters of the API key id, for "Connected · …abcd"
  credentials_ciphertext text not null,   -- base64 AES-GCM ciphertext of {"key","secret"}
  credentials_iv text not null,           -- base64 12-byte IV
  connected_at timestamptz not null default now(),
  last_used_at timestamptz
);
alter table public.guardian_higgsfield_connections enable row level security;

-- The owner may see (and delete, i.e. disconnect) their own row; inserts/updates go through the Edge Function.
drop policy if exists "guardians read own higgsfield connection" on public.guardian_higgsfield_connections;
create policy "guardians read own higgsfield connection" on public.guardian_higgsfield_connections
  for select to authenticated using (user_id = auth.uid());
drop policy if exists "guardians delete own higgsfield connection" on public.guardian_higgsfield_connections;
create policy "guardians delete own higgsfield connection" on public.guardian_higgsfield_connections
  for delete to authenticated using (user_id = auth.uid());
-- Even the owner never gets the ciphertext through the API: column privileges hide it.
revoke all on public.guardian_higgsfield_connections from anon, authenticated;
grant select (user_id, key_hint, connected_at, last_used_at) on public.guardian_higgsfield_connections to authenticated;
grant delete on public.guardian_higgsfield_connections to authenticated;

-- One row per generation, so progress survives a page reload and the Guardian keeps a history.
create table if not exists public.guardian_video_jobs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  brand_id uuid references public.guide_brands(id) on delete set null,
  request_id text,                        -- Higgsfield request id
  model text not null,
  prompt text not null,
  aspect_ratio text not null check (aspect_ratio in ('9:16', '4:5', '1:1', '16:9')),
  duration_seconds int not null default 5,
  image_url text,
  status text not null default 'queued' check (status in ('queued', 'in_progress', 'completed', 'failed', 'nsfw', 'canceled')),
  video_url text,                         -- Higgsfield's result URL (kept by them for at least 7 days)
  storage_path text,                      -- our copy in the private guardian-videos bucket
  error text,
  mock boolean not null default false,    -- true when generated by the function's mock mode (no credits spent)
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists guardian_video_jobs_user_idx on public.guardian_video_jobs(user_id, created_at desc);
alter table public.guardian_video_jobs enable row level security;
drop policy if exists "guardians read own video jobs" on public.guardian_video_jobs;
create policy "guardians read own video jobs" on public.guardian_video_jobs
  for select to authenticated using (user_id = auth.uid());
revoke all on public.guardian_video_jobs from anon, authenticated;
grant select on public.guardian_video_jobs to authenticated;

-- Private bucket for finished videos; only the Edge Function (service role) writes or signs links to it.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('guardian-videos', 'guardian-videos', false, 209715200, array['video/mp4'])
on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;
