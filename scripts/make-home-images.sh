#!/usr/bin/env bash
# Regenerates the homepage's optimised images from the PNG masters in src/assets (kept as the sources):
#   public/images/hero/cover-{960,1440,1920}.webp   the hero cover (a smooth gradient: high quality, sharp YUV, or it bands)
#   public/images/app/{need,risk,meal}-{400,600,900}.webp   the three app screenshots in the "what you get" section
#   src/config/homeImagePlaceholders.ts              ~200-byte blurred WebP data URIs, shown while the real image loads
# Needs cwebp (brew install webp). Run from the repo root; commit the output.
set -euo pipefail
cd "$(dirname "$0")/.."
command -v cwebp >/dev/null || { echo "cwebp not found: brew install webp" >&2; exit 1; }

HERO=src/assets/5f38caf68dd6b8af22362056b70854ea4cf4b933.png
# name:master (plain list, so it also runs on the bash 3.2 that macOS ships)
SHOTS="need:src/assets/f103676152ae3299f7a7f1ac2b178b16e80fc270.png risk:src/assets/95040abfc382a9000163603b0406e99ced704e94.png meal:src/assets/0d90de2a9245f9d68e76a732655874812e689495.png"
# need = Vitamin A (green), risk = Phthalate (red), meal = Bulgar salad result
mkdir -p public/images/hero public/images/app

for w in 960 1440 1920; do
  cwebp -quiet -q 86 -m 6 -sharp_yuv -sns 0 -f 0 -resize "$w" 0 "$HERO" -o "public/images/hero/cover-$w.webp"
done
for pair in $SHOTS; do
  for w in 400 600 900; do
    cwebp -quiet -q 80 -m 6 -sharp_yuv -resize "$w" 0 "${pair#*:}" -o "public/images/app/${pair%%:*}-$w.webp"
  done
done

lqip() { # file width -> data URI
  local tmp; tmp=$(mktemp -t lqip).webp
  cwebp -quiet -q 30 -m 6 -resize "$2" 0 "$1" -o "$tmp"
  printf 'data:image/webp;base64,%s' "$(base64 < "$tmp" | tr -d '\n')"
  rm -f "$tmp"
}
{
  echo "// Generated by scripts/make-home-images.sh. Do not edit by hand."
  echo "export const HERO_LQIP = '$(lqip "$HERO" 32)';"
  for pair in $SHOTS; do
    echo "export const APP_$(echo "${pair%%:*}" | tr a-z A-Z)_LQIP = '$(lqip "${pair#*:}" 16)';"
  done
} > src/config/homeImagePlaceholders.ts
echo "done"
